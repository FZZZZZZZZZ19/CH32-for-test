/*********************************************************************************************************************
* 文件名称          app_crc32
* 说明              CRC-32/ISO-HDLC（反射多项式 0xEDB88320，初值/终值取反）
*                   标准向量："123456789" -> 0xCBF43926
*                   纯逻辑模块：不包含任何硬件头文件，可在 PC 上用 gcc 单测
********************************************************************************************************************/
#ifndef APP_CRC32_H
#define APP_CRC32_H

#include <stdint.h>

/*-------------------------------------------------------------------------------------------------------------------
* 函数简介     CRC-32 计算（内部先做初值取反、最后再取反）
* 参数说明     data        数据首地址
* 参数说明     len         数据长度（字节）
* 返回参数     uint32_t    CRC32 结果
*------------------------------------------------------------------------------------------------------------------*/
uint32_t app_crc32 (const uint8_t *data, uint16_t len);

/*-------------------------------------------------------------------------------------------------------------------
* 函数简介     CRC-32 增量计算（用于分段校验）
* 参数说明     crc         上一段的中间结果（首段传 0xFFFFFFFF）
* 参数说明     data        数据首地址
* 参数说明     len         数据长度（字节）
* 返回参数     uint32_t    新的中间结果（未做终值取反）
*------------------------------------------------------------------------------------------------------------------*/
uint32_t app_crc32_update (uint32_t crc, const uint8_t *data, uint16_t len);

#endif
